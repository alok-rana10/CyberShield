def normalize_finding_payload(
    title: str,
    description: str,
    severity: str | FindingSeverity,
    category: str = "general",
    source_module: str = "manual",
    affected_resource: Optional[str] = None,
    remediation: str = "",
    evidence: Optional[str] = None,
    cwe_id: Optional[str] = None,
    status: str | FindingStatus = FindingStatus.OPEN,
) -> Dict[str, Any]:
    """Normalize finding parameters generated by automated modules or manual entry.

    Ensures standardized severity, status casing, and bounded fields across:
    - Network Scanner
    - Web Security Header Analyzer
    - File Integrity Monitor
    - Defensive Log Analyzer
    - Password Security Analyzer
    """
    raw_sev = severity.value.lower() if hasattr(severity, "value") else str(severity).lower()
    valid_severities = {s.value for s in FindingSeverity}
    normalized_sev = raw_sev if raw_sev in valid_severities else FindingSeverity.MEDIUM.value

    raw_status = status.value.lower() if hasattr(status, "value") else str(status).lower()
    valid_statuses = {st.value for st in FindingStatus}
    normalized_status = raw_status if raw_status in valid_statuses else FindingStatus.OPEN.value

    return {
        "title": title.strip()[:255],
        "description": description.strip(),
        "severity": normalized_sev,
        "category": category.strip().lower()[:100],
        "source_module": source_module.strip().lower()[:50],
        "affected_resource": affected_resource.strip()[:255] if affected_resource else None,
        "remediation": remediation.strip(),
        "evidence": evidence.strip() if evidence else None,
        "cwe_id": cwe_id.strip()[:50] if cwe_id else None,
        "status": normalized_status,
    }


class FindingService:
    """Service providing core business operations for Security Findings and Dashboard."""

    @staticmethod
    def create_finding(
        db: Session,
        finding_in: FindingCreate,
        current_user: User,
        request: Optional[Request] = None,
    ) -> SecurityFinding:
        """Create a new security finding and persist immutable audit record."""
        normalized = normalize_finding_payload(
            title=finding_in.title,
            description=finding_in.description,
            severity=finding_in.severity,
            category=finding_in.category,
            source_module=finding_in.source_module,
            affected_resource=finding_in.affected_resource,
            remediation=finding_in.remediation,
            evidence=finding_in.evidence,
            cwe_id=finding_in.cwe_id,
            status=finding_in.status,
        )

        db_finding = SecurityFinding(
            user_id=current_user.id,
            title=normalized["title"],
            description=normalized["description"],
            severity=normalized["severity"],
            category=normalized["category"],
            source_module=normalized["source_module"],
            affected_resource=normalized["affected_resource"],
            remediation=normalized["remediation"],
            evidence=normalized["evidence"],
            cwe_id=normalized["cwe_id"],
            status=normalized["status"],
            created_at=datetime.now(timezone.utc),
            updated_at=datetime.now(timezone.utc),
            resolved_at=(
                datetime.now(timezone.utc)
                if normalized["status"] == FindingStatus.RESOLVED.value
                else None
            ),
        )
        db.add(db_finding)
        db.commit()
        db.refresh(db_finding)

        # Audit Trail
        ip = get_client_ip(request) if request else "127.0.0.1"
        ua = get_user_agent(request) if request else "Internal Service"
        record_audit_log(
            db=db,
            action="FINDING_CREATED",
            resource_type="FINDING",
            resource_id=db_finding.id,
            status_code=201,
            ip_address=ip,
            user_id=current_user.id,
            user_agent=ua,
            details={
                "title": db_finding.title,
                "severity": db_finding.severity,
                "category": db_finding.category,
                "source_module": db_finding.source_module,
                "affected_resource": db_finding.affected_resource,
            },
        )

        return db_finding

    @staticmethod
    def get_finding_by_id(db: Session, finding_id: str) -> Optional[SecurityFinding]:
        """Fetch finding by primary key."""
        return db.query(SecurityFinding).filter(SecurityFinding.id == finding_id).first()

    @staticmethod
    def list_findings(
        db: Session,
        page: int = 1,
        size: int = 20,
        severity: Optional[str] = None,
        status: Optional[str] = None,
        category: Optional[str] = None,
        source_module: Optional[str] = None,
        search: Optional[str] = None,
    ) -> FindingListResponse:
        """Query paginated security findings with defensive filtering."""
        query = db.query(SecurityFinding)

        if severity:
            query = query.filter(SecurityFinding.severity == severity.lower())
        if status:
            query = query.filter(SecurityFinding.status == status.lower())
        if category:
            query = query.filter(SecurityFinding.category.ilike(f"%{category}%"))
        if source_module:
            query = query.filter(SecurityFinding.source_module == source_module.lower())
        if search:
            search_pattern = f"%{search.strip()}%"
            query = query.filter(
                or_(
                    SecurityFinding.title.ilike(search_pattern),
                    SecurityFinding.affected_resource.ilike(search_pattern),
                    SecurityFinding.description.ilike(search_pattern),
                    SecurityFinding.cwe_id.ilike(search_pattern),
                )
            )

        total = query.count()
        pages = (total + size - 1) // size if total > 0 else 1
        offset = (page - 1) * size

        items = query.order_by(SecurityFinding.created_at.desc()).offset(offset).limit(size).all()

        return FindingListResponse(
            items=[FindingResponse.model_validate(f) for f in items],
            total=total,
            page=page,
            size=size,
            pages=pages,
        )

    @staticmethod
    def update_finding(
        db: Session,
        finding: SecurityFinding,
        update_in: FindingUpdate,
        current_user: User,
        request: Optional[Request] = None,
    ) -> SecurityFinding:
        """Update finding content fields and record audit trail."""
        update_data = update_in.model_dump(exclude_unset=True)

        changed_fields: List[str] = []
        for field, value in update_data.items():
            if value is not None:
                if field == "severity":
                    value = str(
                        value.value if isinstance(value, FindingSeverity) else value
                    ).lower()
                setattr(finding, field, value)
                changed_fields.append(field)

        finding.updated_at = datetime.now(timezone.utc)
        db.commit()
        db.refresh(finding)

        # Audit Trail
        ip = get_client_ip(request) if request else "127.0.0.1"
        ua = get_user_agent(request) if request else "Internal Service"
        record_audit_log(
            db=db,
            action="FINDING_UPDATED",
            resource_type="FINDING",
            resource_id=finding.id,
            status_code=200,
            ip_address=ip,
            user_id=current_user.id,
            user_agent=ua,
            details={
                "changed_fields": changed_fields,
                "title": finding.title,
                "severity": finding.severity,
            },
        )

        return finding

    @staticmethod
    def update_status(
        db: Session,
        finding: SecurityFinding,
        status_in: FindingStatusUpdate,
        current_user: User,
        request: Optional[Request] = None,
    ) -> SecurityFinding:
        """Update finding lifecycle state and manage resolution timestamps."""
        old_status = finding.status
        new_status = status_in.status.value.lower()

        finding.status = new_status
        finding.updated_at = datetime.now(timezone.utc)

        if new_status == FindingStatus.RESOLVED.value:
            finding.resolved_at = datetime.now(timezone.utc)
        else:
            # Reopening or marking as accepted clears resolved_at
            finding.resolved_at = None

        db.commit()
        db.refresh(finding)

        # Audit Trail
        ip = get_client_ip(request) if request else "127.0.0.1"
        ua = get_user_agent(request) if request else "Internal Service"
        record_audit_log(
            db=db,
            action="FINDING_STATUS_CHANGED",
            resource_type="FINDING",
            resource_id=finding.id,
            status_code=200,
            ip_address=ip,
            user_id=current_user.id,
            user_agent=ua,
            details={
                "old_status": old_status,
                "new_status": new_status,
                "resolution_notes": status_in.resolution_notes,
                "title": finding.title,
            },
        )

        return finding

    @staticmethod
    def delete_finding(
        db: Session,
        finding: SecurityFinding,
        current_user: User,
        request: Optional[Request] = None,
    ) -> None:
        """Permanently delete finding (Admin privileged) with audit logging."""
        finding_id = finding.id
        finding_title = finding.title

        db.delete(finding)
        db.commit()

        # Audit Trail
        ip = get_client_ip(request) if request else "127.0.0.1"
        ua = get_user_agent(request) if request else "Internal Service"
        record_audit_log(
            db=db,
            action="FINDING_DELETED",
            resource_type="FINDING",
            resource_id=finding_id,
            status_code=200,
            ip_address=ip,
            user_id=current_user.id,
            user_agent=ua,
            details={
                "title": finding_title,
                "deleted_by": current_user.email,
            },
        )

    @staticmethod
    def get_dashboard_summary(db: Session) -> DashboardSummaryResponse:
        """Generate aggregated security dashboard metrics via efficient SQL grouping."""
        # Severity Counts
        sev_rows = (
            db.query(SecurityFinding.severity, func.count(SecurityFinding.id))
            .group_by(SecurityFinding.severity)
            .all()
        )
        sev_map = {str(k).lower(): count for k, count in sev_rows}

        severity_counts = SeverityCounts(
            critical=sev_map.get("critical", 0),
            high=sev_map.get("high", 0),
            medium=sev_map.get("medium", 0),
            low=sev_map.get("low", 0),
            informational=sev_map.get("informational", 0),
        )

        # Status Counts
        status_rows = (
            db.query(SecurityFinding.status, func.count(SecurityFinding.id))
            .group_by(SecurityFinding.status)
            .all()
        )
        status_map = {str(k).lower(): count for k, count in status_rows}

        status_counts = StatusCounts(
            open=status_map.get("open", 0),
            resolved=status_map.get("resolved", 0),
            accepted=status_map.get("accepted", 0),
        )

        # Category Counts
        cat_rows = (
            db.query(SecurityFinding.category, func.count(SecurityFinding.id))
            .group_by(SecurityFinding.category)
            .all()
        )
        by_category = {str(k): count for k, count in cat_rows}

        # Source Module Counts
        src_rows = (
            db.query(SecurityFinding.source_module, func.count(SecurityFinding.id))
            .group_by(SecurityFinding.source_module)
            .all()
        )
        by_source = {str(k): count for k, count in src_rows}

        # Recent 5 Findings
        recent_models = (
            db.query(SecurityFinding).order_by(SecurityFinding.created_at.desc()).limit(5).all()
        )
        recent_findings = [FindingResponse.model_validate(f) for f in recent_models]

        total_findings = sum(sev_map.values())

        # Defensive Posture Score Calculation:
        # Base 100 points, penalty for open unmitigated issues:
        # Open Critical: -25 pts each
        # Open High: -10 pts each
        # Open Medium: -4 pts each
        # Open Low: -1 pt each
        open_findings = (
            db.query(SecurityFinding.severity, func.count(SecurityFinding.id))
            .filter(SecurityFinding.status == FindingStatus.OPEN.value)
            .group_by(SecurityFinding.severity)
            .all()
        )
        open_sev_map = {str(k).lower(): count for k, count in open_findings}

        penalty = (
            open_sev_map.get("critical", 0) * 25
            + open_sev_map.get("high", 0) * 10
            + open_sev_map.get("medium", 0) * 4
            + open_sev_map.get("low", 0) * 1
        )
        posture_score = max(0, 100 - penalty)

        return DashboardSummaryResponse(
            total_findings=total_findings,
            severity_counts=severity_counts,
            status_counts=status_counts,
            recent_findings=recent_findings,
            by_category=by_category,
            by_source=by_source,
            posture_score=posture_score,
        )
